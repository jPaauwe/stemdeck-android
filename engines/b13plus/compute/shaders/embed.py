#!/usr/bin/env python3
"""Compiles the compute shaders and writes ../spirv.h, so building the
engine needs no shader compiler.

    python3 embed.py [path to glslangValidator or glslang]
"""
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

here = Path(__file__).resolve().parent
tool = sys.argv[1] if len(sys.argv) > 1 else (shutil.which("glslangValidator") or shutil.which("glslang"))
if not tool:
    sys.exit("glslangValidator not found")
out = ["// Generated by shaders/embed.py from the .comp files. Do not edit.", "#pragma once", "#include <cstdint>", ""]
for comp in sorted(here.glob("*.comp")):
    with tempfile.TemporaryDirectory() as tmp:
        spv = Path(tmp) / "out.spv"
        subprocess.run([tool, "-V", "--target-env", "vulkan1.1", "-o", str(spv), str(comp)], check=True,
                       stdout=subprocess.DEVNULL)
        data = spv.read_bytes()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    name = f"kSpirv_{comp.stem}"
    out.append(f"static const uint32_t {name}[] = {{")
    for i in range(0, len(words), 8):
        out.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
    out.append("};")
    out.append("")
(here.parent / "spirv.h").write_text("\n".join(out))
print("wrote", here.parent / "spirv.h")
